fn vegetation_patches_match_the_vanilla_feature_cell_for_cell() {
    let bench = Bench::new();
    for (name, feature, seed, count, hash) in REFERENCE {
        let (spec, origin) = scene(name);
        assert_eq!(
            fingerprint(&bench, &spec, feature, origin, seed, (0, 40)),
            (count, hash),
            "{name} {feature} seed {seed}"
        );
    }
}
