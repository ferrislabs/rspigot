const FLAT: &str = "9:stone";
const ROUGH: &str = "9:stone;4..6/10/4..8=stone;12..14/9/6..9=air;10..11/9/10..11=air;2..3/10..11/10..12=stone;9/10/9=stone;13..15/10/3..5=dirt";
const MIXED: &str = "9:stone;4..12/9/4..12=dirt;8..14/9/8..14=gravel;6..9/9/6..9=oak_planks;12/9/2..4=glass;0..4/9/10..14=moss_block";
const ROOM: &str = "30:stone;-12..28/10..16/-12..28=air";

fn scene(name: &str) -> (String, (i32, i32, i32)) {
    let floor = (8, 10, 8);
    let roof = (8, 16, 8);
    match name {
        "flat" | "pool" => (FLAT.to_owned(), floor),
        "rough" | "poolrough" => (ROUGH.to_owned(), floor),
        "mixed" | "poolmixed" => (MIXED.to_owned(), floor),
        "lowdrop" => ("9:stone;7..9/9/7..9=air;7..9/8/7..9=air".to_owned(), floor),
        "roof" => (ROOM.to_owned(), roof),
        "roofy" => (
            format!(
                "{ROOM};4..6/14..16/4..8=stone;12..14/15..16/6..9=dirt;10..11/16/10..11=air;9/16/9=stone"
            ),
            roof,
        ),
        _ => (
            format!("{ROOM};4..12/17/4..12=dirt;8..14/17/8..14=gravel;6..9/17/6..9=oak_planks"),
            roof,
        ),
    }
}

