#[test]
fn ice_features_match_the_vanilla_feature_cell_for_cell() {
    let bench = Bench::new();
    for (name, feature, seed, count, hash) in REFERENCE {
        let (spec, origin, band) = scene(name);
        assert_eq!(
            fingerprint(&bench, &spec, feature, origin, seed, band),
            (count, hash),
            "{name} {feature} seed {seed}"
        );
    }
}
