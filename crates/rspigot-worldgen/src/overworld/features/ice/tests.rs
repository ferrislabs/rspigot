const OCEAN: &str = "30:stone,31:sand,62:water";
const SNOW: &str = "68:stone,69:snow_block";

fn scene(name: &str) -> (String, (i32, i32, i32), (i32, i32)) {
    let ocean = |extra: &str| format!("{OCEAN};{extra}");
    match name {
        "ocean" => (OCEAN.to_owned(), (8, 63, 8), (30, 110)),
        "snow" => (SNOW.to_owned(), (8, 70, 8), (40, 130)),
        "pit" => (
            format!("{SNOW};4..12/64..69/4..12=air;4..12/63/4..12=snow_block"),
            (8, 70, 8),
            (40, 130),
        ),
        "bare" => ("68:stone,69:grass_block".to_owned(), (8, 70, 8), (40, 130)),
        "packed" => (ocean("9/45/8=packed_ice"), (8, 45, 8), (30, 110)),
        "surface" => (
            ocean("6..12/62/6..12=ice;9/60/8=packed_ice;8/60/9=packed_ice"),
            (8, 61, 8),
            (30, 110),
        ),
        "low" => (ocean("9/62/8=packed_ice"), (8, 62, 8), (30, 110)),
        "high" => (ocean("9/63/8=packed_ice"), (8, 63, 8), (30, 110)),
        "dry" => (
            ocean("9/45/8=packed_ice;7..9/44..46/7..9=air"),
            (8, 45, 8),
            (30, 110),
        ),
        _ => (OCEAN.to_owned(), (8, 45, 8), (30, 110)),
    }
}

