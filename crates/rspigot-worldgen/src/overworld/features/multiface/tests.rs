#[test]
fn scattered_growths_match_the_vanilla_feature_cell_for_cell() {
    let bench = Bench::new();
    let area = [4, 10, 4, 24, 14, 24];
    for (name, feature, seed, count, hash) in SCATTERED {
        let spec = match name {
            "room" => ROOM.to_owned(),
            "mixed" => MIXED.to_owned(),
            _ if feature == "glow_lichen" => format!("{ROOM};4..24/10..14/4..24=water"),
            _ => format!("{ROOM};4..24/10..12/4..24=water"),
        };
        assert_eq!(
            scatter_fingerprint(&bench, &spec, feature, area, 80, seed, (0, 40)),
            (count, hash),
            "{name} {feature} seed {seed}"
        );
    }
}
