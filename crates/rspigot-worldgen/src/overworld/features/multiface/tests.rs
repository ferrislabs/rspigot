const ROOM: &str = "30:stone;4..24/10..14/4..24=air";
const MIXED: &str = "30:stone;4..24/10..14/4..24=air;8..9/10..14/8..20=andesite;14..16/12..14/10..12=dripstone_block;20..22/10..14/10..12=glass;18/10..13/14..18=oak_leaves;6..7/13/6..22=stone_slab;12..13/10..11/4..8=stone_slab";

fn scene(name: &str) -> (String, (i32, i32, i32)) {
    let with = |extra: &str| format!("{ROOM};{extra}");
    match name {
        "lichen_ceiling" => (ROOM.to_owned(), (14, 14, 14)),
        "lichen_wall" => (ROOM.to_owned(), (4, 12, 14)),
        "lichen_corner" => (ROOM.to_owned(), (4, 14, 4)),
        "lichen_drowned" => (with("4..24/10..14/4..24=water"), (14, 14, 14)),
        "lichen_mixed" => (MIXED.to_owned(), (10, 12, 12)),
        "lichen_glass" => (MIXED.to_owned(), (19, 13, 11)),
        "lichen_solid" => (ROOM.to_owned(), (14, 12, 14)),
        "vein_floor" => (ROOM.to_owned(), (14, 10, 14)),
        "vein_ceiling" => (ROOM.to_owned(), (14, 14, 14)),
        "vein_mixed" => (MIXED.to_owned(), (10, 11, 12)),
        "vein_drowned" => (with("4..24/10..12/4..24=water"), (14, 10, 14)),
        _ => (
            with("4..24/11/4..24=fire;12..16/10..13/12..16=lava"),
            (14, 10, 14),
        ),
    }
}

