#[test]
fn fallen_trees_match_the_vanilla_feature_cell_for_cell() {
    let bench = Bench::new();
    for (name, feature, seed, count, hash) in REFERENCE {
        assert_eq!(
            fingerprint(&bench, &scene(name), feature, (8, 70, 8), seed, (40, 130)),
            (count, hash),
            "{name} {feature} seed {seed}"
        );
    }
}
